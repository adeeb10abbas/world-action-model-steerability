"""Automated blinded forecast labeling with open-weight VLMs (disclosed amendment A11; replaces human annotators).

Each labeler sees exactly what a human annotator would: packets/<Aid>/legend.png and the mapped forecast frames of
forecast.mkv. It never sees the key, prompt, model, goal or outcome. Outputs are schema-constrained to rubric v2.

    label:      python -m experiments.robolab_workshop.vlm_label label --annotation $R/annotation \
                    --endpoints http://ip:port,... --model NAME --out $R/annotation/labels_vlm_a.jsonl
    adjudicate: ... adjudicate --annotation $R/annotation --labels a.jsonl b.jsonl --endpoints ... --model NAME \
                    --out $R/annotation/labels_vlm_adjudicated.jsonl
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import io
import itertools
import json
import random
import subprocess
import threading
import time
import urllib.request
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

import numpy as np

from .annotation import FIELDS
from .recording import FFMPEG

RUBRIC = Path(__file__).with_name("annotation_rubric.json")
N_FRAMES = 8
H, W = 544, 640

SYSTEM = """You are a careful annotator of robot video forecasts. You label only what is visible. You are never told the robot's instruction and must not guess it.

Images you receive:
1. LEGEND: the real starting scene from two exterior cameras side by side. Yellow circles with numbers identify the task objects. The cyan arrow points to the robot's LEFT. The magenta arrow points AWAY from the robot ("farther"). Directions are always in this robot frame, never in image left/right.
2. FORECAST frames, in time order: a video generated by a robot model predicting what will happen. Each frame has the wrist camera in the top pane and the same two exterior cameras side by side in the bottom panes. Objects may look slightly different in style from the legend; identify them by position, shape and colour.

Rules: RGB cannot show support forces or hidden containment; prefer "ambiguous" or "unknown" over guessing. "moving_object" is the legend object displaced by the robot; "none" if nothing is displaced; "multiple" if several are displaced comparably. "direction" is the dominant horizontal displacement of the moving object in the robot frame (use the arrows); "up_only" if lifted without clear horizontal travel. "visible_final_relation" is the relation, at the LAST forecast frame, of the moving object with respect to "relation_object" (e.g. left_of means the moving object is to the robot-left of relation_object). "possible_release": the gripper visibly opens and separates from the object. "missing_object": a legend object vanishes or becomes unrecognisable while not occluded. "hallucinated_object": a new object appears that is not in the legend. "unknown_reason" explains any unknown field, else "none".
First write brief visual observations, then the labels."""


def _rubric_values(field: str) -> list[str]:
    return json.loads(RUBRIC.read_text())["fields"][field]["values"]


def schema(legend_numbers: list[int]) -> dict:
    nums = [str(n) for n in legend_numbers]
    props = {"observations": {"type": "string", "maxLength": 900}}
    for f in FIELDS:
        vals = [v for v in _rubric_values(f) if v != "<legend number>"]
        if "<legend number>" in _rubric_values(f):
            vals = nums + vals
        props[f] = {"type": "string", "enum": vals}
    return {"type": "object", "properties": props, "required": ["observations"] + FIELDS, "additionalProperties": False}


def _png_b64(arr: np.ndarray) -> str:
    from PIL import Image
    buf = io.BytesIO()
    Image.fromarray(arr).save(buf, format="PNG")
    return base64.b64encode(buf.getvalue()).decode()


def forecast_frames(pdir: Path, n_total: int) -> tuple[list[int], list[np.ndarray]]:
    raw = subprocess.run([FFMPEG, "-nostdin", "-hide_banner", "-loglevel", "error", "-i", str(pdir / "forecast.mkv"), "-f", "rawvideo",
                          "-pix_fmt", "rgb24", "-"], capture_output=True, check=True).stdout
    video = np.frombuffer(raw, np.uint8).reshape(-1, H, W, 3)
    idx = sorted(set(np.linspace(0, len(video) - 1, min(N_FRAMES, len(video))).round().astype(int).tolist()))
    return idx, [video[i] for i in idx]


def content(pdir: Path, extra_text: str = "") -> list[dict]:
    from PIL import Image
    meta = json.loads((pdir / "packet.json").read_text())
    legend = np.asarray(Image.open(pdir / "legend.png").convert("RGB"))
    idx, frames = forecast_frames(pdir, meta["frames"])
    parts = [{"type": "text", "text": f"LEGEND (object numbers: {', '.join(map(str, meta['legend_numbers']))}):"},
             {"type": "image_url", "image_url": {"url": "data:image/png;base64," + _png_b64(legend)}}]
    for j, (i, fr) in enumerate(zip(idx, frames)):
        parts += [{"type": "text", "text": f"FORECAST frame {j + 1}/{len(idx)} (t={i / 15:.2f}s)"
                   + (" - LAST FRAME" if j == len(idx) - 1 else "") + ":"},
                  {"type": "image_url", "image_url": {"url": "data:image/png;base64," + _png_b64(fr)}}]
    parts.append({"type": "text", "text": extra_text or "Label this forecast. Respond with the JSON object only."})
    return parts


class Client:
    def __init__(self, endpoints: list[str], model: str, extra_body: dict) -> None:
        self.cycle, self.lock = itertools.cycle(endpoints), threading.Lock()
        self.model, self.extra = model, extra_body

    def chat(self, parts: list[dict], sch: dict, retries: int = 4) -> tuple[dict, dict]:
        body = {"model": self.model, "temperature": 0.0, "max_tokens": 1200, "seed": 0,
                "messages": [{"role": "system", "content": SYSTEM}, {"role": "user", "content": parts}],
                "response_format": {"type": "json_schema", "json_schema": {"name": "forecast_label", "schema": sch, "strict": True}},
                **self.extra}
        err = None
        for attempt in range(retries):
            # Retries after a failed deterministic call sample at low temperature with a new seed.
            data = json.dumps(body if attempt == 0 else {**body, "temperature": 0.2, "seed": attempt}).encode()
            with self.lock:
                ep = next(self.cycle)
            try:
                req = urllib.request.Request(ep.rstrip("/") + "/v1/chat/completions", data=data,
                                             headers={"Content-Type": "application/json"})
                with urllib.request.urlopen(req, timeout=600) as r:
                    resp = json.loads(r.read())
                text = resp["choices"][0]["message"]["content"]
                return json.loads(text[text.find("{"): text.rfind("}") + 1]), {"endpoint": ep, "usage": resp.get("usage"),
                                                                              "finish_reason": resp["choices"][0].get("finish_reason")}
            except Exception as e:  # noqa: BLE001 - retried, then surfaced as an infrastructure failure
                err = repr(e)
                time.sleep(2 * (attempt + 1))
        raise RuntimeError(err)


def _done(out: Path) -> set[str]:
    if not out.exists():
        return set()
    return {json.loads(x)["annotation_id"] for x in out.read_text().splitlines() if x.strip() and '"error"' not in x}


def _run(items, fn, out: Path, concurrency: int) -> None:
    lock = threading.Lock()
    n = ok = 0
    t0 = time.time()
    with ThreadPoolExecutor(concurrency) as ex, open(out, "a") as f:
        futs = {ex.submit(fn, it): it for it in items}
        for fu in as_completed(futs):
            rec = fu.result()
            with lock:
                f.write(json.dumps(rec, sort_keys=True) + "\n")
                f.flush()
                n += 1
                ok += "error" not in rec
                if n % 25 == 0 or n == len(items):
                    print(json.dumps({"done": n, "ok": ok, "of": len(items), "elapsed_s": round(time.time() - t0)}), flush=True)


def _packets(annotation: Path) -> list[Path]:
    return sorted(p for p in (annotation / "packets").iterdir() if (p / "packet.json").exists())


def label(args) -> None:
    client = Client(args.endpoints.split(","), args.model, json.loads(args.extra_body))
    todo = [p for p in _packets(args.annotation) if p.name not in _done(args.out)]
    if args.ids:
        want = [x.strip() for x in args.ids.read_text().split() if x.strip()]
        pos = {a: i for i, a in enumerate(want)}
        todo = sorted((p for p in todo if p.name in pos), key=lambda p: pos[p.name])
    if args.limit:
        todo = todo[:args.limit]
    print(f"{len(todo)} packets to label with {args.model}", flush=True)

    def one(pdir: Path) -> dict:
        meta = json.loads((pdir / "packet.json").read_text())
        try:
            lab, info = client.chat(content(pdir), schema(meta["legend_numbers"]))
            return {"annotation_id": pdir.name, "labeler": args.labeler, "model": args.model,
                    **{f: lab[f] for f in FIELDS}, "observations": lab.get("observations", ""), "info": info}
        except Exception as e:  # noqa: BLE001
            return {"annotation_id": pdir.name, "labeler": args.labeler, "model": args.model, "error": repr(e)}

    _run(todo, one, args.out, args.concurrency)


def _load(path: Path) -> dict:
    return {r["annotation_id"]: r for r in (json.loads(x) for x in path.read_text().splitlines() if x.strip())
            if "error" not in r}


def adjudicate(args) -> None:
    a, b = (_load(p) for p in args.labels)
    client = Client(args.endpoints.split(","), args.model, json.loads(args.extra_body))
    done = _done(args.out)
    todo = []
    for aid in sorted(set(a) & set(b)):
        diff = [f for f in FIELDS if a[aid][f] != b[aid][f]]
        if diff and aid not in done:
            todo.append((aid, diff))
    print(f"{len(todo)} disagreeing packets to adjudicate", flush=True)

    def one(item) -> dict:
        aid, diff = item
        pdir = args.annotation / "packets" / aid
        meta = json.loads((pdir / "packet.json").read_text())
        rng = random.Random(int(hashlib.sha256(aid.encode()).hexdigest(), 16))
        first, second = (a[aid], b[aid]) if rng.random() < 0.5 else (b[aid], a[aid])
        sch = schema(meta["legend_numbers"])
        for f in FIELDS:
            if f in diff:
                sch["properties"][f]["enum"] = sorted({first[f], second[f], "unknown"}
                                                      & set(sch["properties"][f]["enum"]))
            else:
                sch["properties"][f]["enum"] = [first[f]]
        cand = "\n".join(f"- {f}: candidate 1 = {first[f]!r}, candidate 2 = {second[f]!r}" for f in diff)
        text = ("Two independent annotators labeled this forecast and disagree on these fields:\n" + cand +
                "\nLook at the images yourself and choose, for each disputed field, the value that the images support, "
                "or 'unknown' if neither is supported. Agreed fields are fixed. Respond with the JSON object only.")
        try:
            lab, info = client.chat(content(pdir, text), sch)
            return {"annotation_id": aid, "labeler": "adjudicator", "model": args.model, "disputed": diff,
                    **{f: lab[f] for f in FIELDS}, "observations": lab.get("observations", ""), "info": info}
        except Exception as e:  # noqa: BLE001
            return {"annotation_id": aid, "labeler": "adjudicator", "model": args.model, "error": repr(e)}

    _run(todo, one, args.out, args.concurrency)


def clean(args) -> None:
    """Latest successful record per annotation id, rubric fields only, for annotation.py unblind."""
    recs = _load(args.src)
    with open(args.dest, "w") as f:
        for aid in sorted(recs):
            f.write(json.dumps({"annotation_id": aid, **{k: recs[aid][k] for k in FIELDS}}, sort_keys=True) + "\n")
    print(f"{len(recs)} labels -> {args.dest}")


def agreement(args) -> None:
    """Per-field raw agreement and Cohen's kappa between the two independent labelers, by window."""
    a, b = (_load(p) for p in args.labels)
    key = {k["annotation_id"]: k for k in (json.loads(x) for x in (args.annotation / "_key" / "key.jsonl").read_text().splitlines())
           if k.get("annotation_id")}
    out = {}
    for window in ("primary", "request0", "all"):
        ids = [i for i in sorted(set(a) & set(b)) if window == "all" or key[i]["window"] == window]
        res = {"n": len(ids)}
        for f in FIELDS:
            xa, xb = [a[i][f] for i in ids], [b[i][f] for i in ids]
            po = sum(p == q for p, q in zip(xa, xb)) / max(len(ids), 1)
            cats = set(xa) | set(xb)
            pe = sum((xa.count(c) / len(ids)) * (xb.count(c) / len(ids)) for c in cats) if ids else 0.0
            res[f] = {"agreement": round(po, 4), "kappa": round((po - pe) / (1 - pe), 4) if pe < 1 else None}
        res["all_fields_agree"] = round(sum(all(a[i][f] == b[i][f] for f in FIELDS) for i in ids) / max(len(ids), 1), 4)
        out[window] = res
    args.dest.write_text(json.dumps(out, indent=2))
    print(json.dumps(out["primary"], indent=1))


def main() -> None:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("label", "adjudicate"):
        s = sub.add_parser(name)
        s.add_argument("--annotation", type=Path, required=True)
        s.add_argument("--endpoints", required=True)
        s.add_argument("--model", required=True)
        s.add_argument("--out", type=Path, required=True)
        s.add_argument("--concurrency", type=int, default=32)
        s.add_argument("--extra-body", default="{}")
        s.add_argument("--limit", type=int, default=0)
        if name == "label":
            s.add_argument("--labeler", required=True)
            s.add_argument("--ids", type=Path, default=None, help="optional file of annotation ids, processed in order")
        else:
            s.add_argument("--labels", type=Path, nargs=2, required=True)
    c = sub.add_parser("clean")
    c.add_argument("--src", type=Path, required=True)
    c.add_argument("--dest", type=Path, required=True)
    g = sub.add_parser("agreement")
    g.add_argument("--annotation", type=Path, required=True)
    g.add_argument("--labels", type=Path, nargs=2, required=True)
    g.add_argument("--dest", type=Path, required=True)
    args = ap.parse_args()
    {"label": label, "adjudicate": adjudicate, "clean": clean, "agreement": agreement}[args.cmd](args)


if __name__ == "__main__":
    main()
